import assert from 'node:assert/strict';
import { loadTsFixture } from './ts-fixture-loader.mjs';
const { goalProgress, goalRingSvg } = loadTsFixture('src/toolbar/goalWidget.ts');
const { goalCurrent, dashboardGoalTarget } = loadTsFixture('src/dashboard/goalBar.ts');
const { normalizeWidgetOrder } = loadTsFixture('src/toolbar/widgetOrder.ts');
assert.deepEqual(normalizeWidgetOrder(['munpia', 'novelpia', 'mode', 'timer']), ['munpia', 'novelpia', 'goal', 'mode', 'timer']);
const order = normalizeWidgetOrder(['timer', 'novelpia', 'munpia']);
assert.equal(order[order.indexOf('novelpia') + 1], 'goal');
assert.equal(goalCurrent({ munpia: 10, novelpia: 7 }, { goalCharBasis: 'novelpia' }), 7);
assert.equal(goalCurrent({ munpia: 10, novelpia: 7 }, {}), 10);
assert.equal(dashboardGoalTarget({ writingGoalChars: 0 }), 10000);
assert.equal(dashboardGoalTarget({ writingGoalChars: 3000 }), 3000);
assert.equal(goalProgress(4200, 5000).remaining, 800);
assert.equal(goalProgress(5100, 5000).reached, true);
assert.equal(goalProgress(100, 0).reached, false);
assert.equal(goalProgress(100, 0).ratio, 0);
assert.equal((goalRingSvg(0.5).match(/is-filled/g) ?? []).length, 6);
assert.equal((goalRingSvg(0.5).match(/is-empty/g) ?? []).length, 6);
console.log('PASS goal progress, shared dashboard goal, basis, ring and widget migration');
