// Search metadata comes from the same renderers used by both SDK generations.
import fs from 'node:fs';
import ts from 'typescript';

const source = fs.readFileSync('src/settings/index.ts', 'utf8');
const ast = ts.createSourceFile('index.ts', source, ts.ScriptTarget.Latest, true);
const methods = new Map();
const visit = (node, callback) => { callback(node); node.forEachChild(child => visit(child, callback)); };
visit(ast, node => { if (ts.isMethodDeclaration(node)) methods.set(node.name.getText(ast), node); });
const literal = node => node && ts.isStringLiteralLike(node) ? node.text : undefined;
const calls = node => { const found = []; visit(node, child => { if (ts.isCallExpression(child) && ts.isPropertyAccessExpression(child.expression)) found.push(child); }); return found; };
const pages = [];
for (const clause of methods.get('renderPageContent').body.statements.find(ts.isSwitchStatement).caseBlock.clauses) {
	if (!ts.isCaseClause(clause)) continue;
	const id = literal(clause.expression);
	const method = calls(clause).find(call => call.expression.name.text.startsWith('render'))?.expression.name.text;
	if (!method || id === 'main' || pages.some(page => page.method === method)) continue;
	const back = calls(methods.get(method)).find(call => call.expression.name.text === 'addBackButton');
	pages.push({ id, method, name: literal(back?.arguments[1]) ?? id, desc: '', parent: literal(back?.arguments[2]) ?? 'main', group: '', visible: false, mobile: id === 'mobile-fonts', aliases: [] });
}
let navigationOrder = 0;
for (const [method, node] of methods) {
	let group = '';
	for (const call of calls(node)) {
		if (call.expression.name.text === 'addGroupTitle') group = literal(call.arguments[1]) ?? '';
		if (call.expression.name.text !== 'addNavCard') continue;
		const page = pages.find(page => page.id === literal(call.arguments[4]));
		if (!page) continue;
		Object.assign(page, { name: literal(call.arguments[1]), desc: literal(call.arguments[2]), visible: true });
		const parentMethod = page.parent === 'main' ? 'renderMainPage' : pages.find(parent => parent.id === page.parent)?.method;
		if (method === parentMethod) page.group = group;
		if (method === 'renderMainPage') page.order = navigationOrder++;
	}
}
const extras = {
	wiki: ['src/wiki/WikiSettings.ts'],
	plot: ['src/plot-workbook/PlotWorkbookSettings.ts'],
	snapshots: ['src/plot-workbook/PlotWorkbookSettings.ts'],
	ai: ['src/aichat/DeusSettings.ts', 'src/aichat/rag/RagSettings.ts'],
};
for (const page of pages) {
	const labels = new Set();
	const collect = node => {
		for (const call of calls(node)) {
			const name = call.expression.name.text;
			const args = ['addToggle'].includes(name) ? call.arguments.slice(1, 3)
				: ['addGroupTitle', 'addNavCard'].includes(name) ? call.arguments.slice(1, 3)
				: ['setName', 'setDesc', 'setButtonText'].includes(name) ? call.arguments.slice(0, 1) : [];
			for (const arg of args) { const text = literal(arg); if (text) labels.add(text); }
		}
		// Labels in [settingKey, label] tables are rendered through a loop variable.
		visit(node, child => {
			if (!ts.isArrayLiteralExpression(child)) return;
			for (const item of child.elements) {
				const label = literal(item);
				if (label && /[가-힣]/.test(label) && label.length <= 120 && !label.includes('/')) labels.add(label);
			}
		});
	};
	collect(methods.get(page.method));
	for (const filename of extras[page.id] ?? []) collect(ts.createSourceFile(filename, fs.readFileSync(filename, 'utf8'), ts.ScriptTarget.Latest, true));
	page.aliases = [...labels];
	delete page.method;
}
pages.sort((a, b) => (a.order ?? 1000) - (b.order ?? 1000));
for (const page of pages) delete page.order;
const output = '// Generated by scripts/generate-settings-search.mjs. Do not edit.\n'
	+ 'export const SETTINGS_SEARCH_PAGES = ' + JSON.stringify(pages, null, '\t') + ' as const;\n';
const filename = 'src/settings/settingsSearch.generated.ts';
if (process.argv.includes('--check')) {
	if (fs.readFileSync(filename, 'utf8') !== output) throw new Error('Settings search metadata is stale. Run node scripts/generate-settings-search.mjs');
} else fs.writeFileSync(filename, output);
