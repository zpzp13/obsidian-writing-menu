import assert from 'node:assert/strict';
import { loadTsFixture } from './ts-fixture-loader.mjs';
const { findHighlights, removeHighlightMarkup, addHighlightMarkup } = loadTsFixture('src/comments/HighlightAnchors.ts');
const { anchorThreads } = loadTsFixture('src/comments/HighlightAnchoring.ts');
const { filterCards } = loadTsFixture('src/comments/HighlightCommentFilter.ts');
const { normalizeHighlightComments } = loadTsFixture('src/comments/HighlightCommentTypes.ts');
const { parseInlineMarkdown, serializeInlineMarkdown } = loadTsFixture('src/paged/MarkdownInlineFormat.ts');
const thread = (h, id = 't') => ({ id, path: 'note.md', quote: h.text, prefix: h.prefix, suffix: h.suffix, offset: h.from, color: h.color, status: 'open', comments: [{ id: 'c', body: '댓글 찾기', createdAt: 1, updatedAt: 1 }], createdAt: 1, updatedAt: 1 });
const source = '앞 ==하나== 중간 ==🟢둘== 뒤';
const highlights = findHighlights(source);
assert.equal(highlights.length, 2); assert.equal(highlights[1].color, 'green');
assert.equal(source.slice(highlights[0].from, highlights[0].to), '==하나==');
assert.equal(source.slice(highlights[1].from, highlights[1].to), '==🟢둘==');
assert.equal(findHighlights('<mark>셋</mark>')[0].text, '셋');
const fm = '---\ntitle: test\n---\n';
assert.equal(findHighlights(fm + source)[0].from, fm.length + highlights[0].from);
assert.equal(findHighlights('%%==주석 안==%%\n`==코드==`\n~~~\n==펜스==\n~~~').length, 0);
for (const nested of ['**==하나==**', '==**하나**==', '<u>==하나==</u>', '<mark>**하나**</mark>']) {
	const h = findHighlights(nested)[0]; assert(h); assert.equal(h.text, '하나');
	const parsed = parseInlineMarkdown(nested); parsed.highlights = [];
	assert.equal(removeHighlightMarkup(nested, h), serializeInlineMarkdown(parsed));
}
const repeated = '첫 문맥 ==그래== 첫 끝\n둘 문맥 ==그래== 둘 끝', hs = findHighlights(repeated);
const ts = hs.map((h, i) => thread(h, 't' + i));
let result = anchorThreads(ts, findHighlights(repeated.replace('==그래==', '그래')));
assert.equal(result[0].state, 'detached'); assert.equal(result[1].state, 'attached');
const original = '앞 문맥 ==그는 검을 들었다== 뒤 문맥', t = thread(findHighlights(original)[0]);
assert.equal(anchorThreads([t], findHighlights(original.replace('검', '칼')))[0].quoteChanged, true);
assert.equal(anchorThreads([t], [])[0].state, 'detached');
assert.equal(anchorThreads([t], findHighlights(original))[0].state, 'attached');
const removed = removeHighlightMarkup(original, findHighlights(original)[0]);
assert.equal(findHighlights(removed).length, 0);
const state = parseInlineMarkdown(removed), from = state.visible.indexOf(t.quote);
assert.equal(addHighlightMarkup(removed, from, from + t.quote.length, ''), original);
assert.equal(anchorThreads([t], findHighlights('문단\n'.repeat(4000) + original))[0].state, 'attached');
const cards = [{ highlight: highlights[0], thread: thread(highlights[0]) }, { highlight: highlights[1], thread: { ...thread(highlights[1], 'done'), status: 'done' } }, { highlight: highlights[0] }, { thread: thread(highlights[0], 'gone') }];
const filter = { status: 'all', colors: [], query: '' };
assert.equal(filterCards(cards, filter).length, 4);
assert.equal(filterCards(cards, { ...filter, colors: ['green'], status: 'done' }).length, 1);
assert.equal(filterCards(cards, { ...filter, colors: ['green'], status: 'open' }).length, 0);
assert.equal(filterCards(cards, { ...filter, query: '찾기' }).length, 3);
assert.equal(filterCards(cards, { ...filter, status: 'missing' }).length, 1);
assert.equal(filterCards(cards, { ...filter, status: 'open' }).length, 1, 'Uncommented and missing highlights are not open');
const stored = normalizeHighlightComments({ version: 1, threads: { t } });
assert.equal(stored.threads.t.comments.length, 1); assert.notEqual(stored.threads.t, t);
assert.deepEqual(normalizeHighlightComments(undefined), { version: 1, threads: {} });
console.log('PASS source highlight ranges, protected text, markup edits, duplicate/fuzzy/undo anchoring and comment filters');

