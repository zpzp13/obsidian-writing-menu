import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "module";
import { readFile } from 'node:fs/promises';

const licenseNames = ['bootstrap-icons', 'kordoc', 'docx', 'docx-preview', 'markdown-it', 'markdown-it-footnote', 'fflate', 'jszip', 'xmldom'];
const licenseText = (await Promise.all(licenseNames.map(async name => `=== ${name} ===\n${await readFile(`vendor/licenses/${name}.txt`, 'utf8')}`))).join('\n\n');
const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
` + '\n/*! Document export third-party notices\n' + licenseText.replaceAll('*/', '* /') + '\n*/\n';

const prod = (process.argv[2] === 'production');
const mainBuildOptions = {
	banner: {
		js: banner,
	},
	entryPoints: ['main.ts'],
	define: {},
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules],
	format: 'cjs',
	target: 'es2018',
	logLevel: "info",
	// garu_wasm.js의 import.meta.url 사용은 우리가 호출하지 않는 URL-fetch 폴백 경로에만 있음 (항상 initSync에 bytes를 직접 넘김)
	logOverride: { 'empty-import-meta': 'silent' },
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
};

const workerBuildOptions = {
	entryPoints: ['src/repetition/garuWorker.ts'],
	bundle: true,
	platform: 'browser',
	format: 'iife',
	target: 'chrome100',
	logLevel: 'info',
	// 바이트를 직접 전달하므로 wasm-bindgen의 URL 폴백(import.meta.url)은 실행되지 않는다.
	logOverride: { 'empty-import-meta': 'silent' },
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'garu-worker.js',
};

await esbuild.build(workerBuildOptions);
mainBuildOptions.define.__WM_GARU_WORKER_SOURCE__ = JSON.stringify(await readFile('garu-worker.js', 'utf8'));
const documentWorkerBuildOptions = {
	entryPoints: ['src/export/documentWorker.ts'], bundle: true, platform: 'browser', format: 'iife',
	target: 'chrome100', logLevel: 'info', minify: prod, sourcemap: prod ? false : 'inline',
	outfile: 'document-worker.js',
};
await esbuild.build(documentWorkerBuildOptions);
mainBuildOptions.define.__WM_DOCUMENT_WORKER_SOURCE__ = JSON.stringify(await readFile('document-worker.js', 'utf8'));
if (!prod) mainBuildOptions.plugins = [{
	name: 'watch-embedded-document-worker',
	setup(builder) {
		builder.onLoad({ filter: /[\\/]DocumentEngine\.ts$/ }, async args => {
			const result = await esbuild.build({ ...documentWorkerBuildOptions, write: false, metafile: true });
			const source = await readFile(args.path, 'utf8');
			return {
				loader: 'ts', resolveDir: args.path.replace(/[\\/][^\\/]+$/, ''),
				contents: source.replace('declare const __WM_DOCUMENT_WORKER_SOURCE__: string;', `const embeddedDocumentWorkerSource = ${JSON.stringify(result.outputFiles[0].text)};`).replaceAll('__WM_DOCUMENT_WORKER_SOURCE__', 'embeddedDocumentWorkerSource'),
				watchFiles: Object.keys(result.metafile.inputs),
			};
		});
	},
}];

if (prod) {
	// The morphology worker is embedded for the three-file community installer.
	await esbuild.build(mainBuildOptions);
} else {
	const contexts = [];
	try {
		for (const options of [mainBuildOptions, workerBuildOptions]) contexts.push(await esbuild.context(options));
		await Promise.all(contexts.map(context => context.watch()));
	} catch (error) {
		await Promise.all(contexts.map(context => context.dispose()));
		throw error;
	}
}
