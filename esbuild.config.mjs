import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "module";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === 'production');

const mainContext = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules],
	format: 'cjs',
	target: 'es2018',
	logLevel: "info",
	// garu_wasm.js의 import.meta.url 사용은 우리가 호출하지 않는 URL-fetch 폴백 경로에만 있음 (항상 initSync에 bytes를 직접 넘김)
	logOverride: { 'empty-import-meta': 'silent' },
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
});

const workerContext = await esbuild.context({
	entryPoints: ['src/repetition/garuWorker.ts'],
	bundle: true,
	platform: 'browser',
	format: 'iife',
	target: 'chrome100',
	logLevel: 'info',
	// 바이트를 직접 전달하므로 wasm-bindgen의 URL 폴백(import.meta.url)은 실행되지 않는다.
	logOverride: { 'empty-import-meta': 'silent' },
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'garu-worker.js',
});

if (prod) {
	await Promise.all([mainContext.rebuild(), workerContext.rebuild()]);
	await Promise.all([mainContext.dispose(), workerContext.dispose()]);
	process.exit(0);
} else {
	await Promise.all([mainContext.watch(), workerContext.watch()]);
}
